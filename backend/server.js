require('dotenv').config();
if (!process.env.JWT_SECRET || process.env.JWT_SECRET.length < 32) throw new Error('Set JWT_SECRET to a random value at least 32 characters long in backend/.env');
const express = require('express');
const path = require('path');
const cookieParser = require('cookie-parser');
const helmet = require('helmet');
const rateLimit = require('express-rate-limit');
const authRoutes = require('./routes/auth');
const eventRoutes = require('./routes/events');
const registrationRoutes = require('./routes/registrations');
const adminRoutes = require('./routes/admin');
const app = express();
app.disable('x-powered-by');
app.use(helmet({ contentSecurityPolicy: { directives: { defaultSrc:["'self'"], scriptSrc:["'self'"], styleSrc:["'self'","'unsafe-inline'"], imgSrc:["'self'","data:"], connectSrc:["'self'"], objectSrc:["'none'"], baseUri:["'self'"], frameAncestors:["'none'"] } } }));
app.use(express.json({limit:'20kb'}));
app.use(cookieParser());
const authLimiter = rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false,message:{error:'Too many authentication attempts. Please wait and try again.'}});
app.use('/api/auth',authLimiter);
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'College Event Management and Registration System'}));
app.use('/api/auth',authRoutes);
app.use('/api/events',eventRoutes);
app.use('/api/registrations',registrationRoutes);
app.use('/api/admin',adminRoutes);
app.use('/api', (req,res)=>res.status(404).json({error:'API endpoint not found.'}));
app.use(express.static(path.join(__dirname,'..','frontend')));
app.get('/{*path}',(req,res,next)=>{ if(req.path.startsWith('/api/'))return next(); res.sendFile(path.join(__dirname,'..','frontend','index.html')); });
app.use((err,req,res,next)=>{ console.error(`[${new Date().toISOString()}]`,err.message); if(res.headersSent)return next(err); res.status(500).json({error:'An unexpected server error occurred. Check the server terminal for details.'}); });
const port = Number(process.env.PORT)||3000;
app.listen(port,()=>console.log(`CampusConnect running at http://localhost:${port}`));